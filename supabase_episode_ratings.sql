-- Watchlistey Episode Ratings Graph Schema
-- Run this in your Supabase SQL editor to create the Episode Ratings tables

-- 1. Episodes Table
create table if not exists public.episodes (
  id bigint not null,
  show_id bigint not null,
  season_number integer not null,
  episode_number integer not null,
  title text not null,
  air_date date null,
  still_path text null,
  runtime integer null,
  overview text null,
  created_at timestamp with time zone default now(),
  constraint episodes_pkey primary key (id),
  constraint episodes_show_season_ep_key unique (show_id, season_number, episode_number)
);

-- Index for speedy lookups by series and season
create index if not exists idx_episodes_show_season on public.episodes(show_id, season_number);

-- 2. External Ratings Table
create table if not exists public.external_ratings (
  id bigint generated by default as identity not null,
  episode_id bigint not null references public.episodes (id) on delete cascade,
  source text not null default 'TMDB',
  rating numeric(3, 1) not null,
  votes integer not null default 0,
  updated_at timestamp with time zone default now(),
  constraint external_ratings_pkey primary key (id),
  constraint external_ratings_episode_source_key unique (episode_id, source)
);

create index if not exists idx_external_ratings_ep on public.external_ratings(episode_id);

-- 3. Watchlistey User Ratings Table
create table if not exists public.watchlistey_user_ratings (
  id bigint generated by default as identity not null,
  episode_id bigint not null references public.episodes (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  rating numeric(3, 1) not null check (rating >= 1.0 and rating <= 10.0),
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now(),
  constraint watchlistey_user_ratings_pkey primary key (id),
  constraint watchlistey_user_ratings_ep_user_key unique (episode_id, user_id)
);

create index if not exists idx_user_ratings_ep on public.watchlistey_user_ratings(episode_id);
create index if not exists idx_user_ratings_user on public.watchlistey_user_ratings(user_id);

-- 4. Aggregated Rating Statistics Table
create table if not exists public.aggregated_episode_rating_stats (
  episode_id bigint not null references public.episodes (id) on delete cascade,
  average_external_rating numeric(3, 1) default 0.0,
  average_watchlistey_rating numeric(3, 1) default 0.0,
  external_votes integer default 0,
  watchlistey_votes integer default 0,
  last_updated timestamp with time zone default now(),
  constraint aggregated_episode_rating_stats_pkey primary key (episode_id)
);

-- 5. Trigger Function to automatically update Watchlistey aggregates
create or replace function public.recalculate_watchlistey_episode_stats()
returns trigger as $$
declare
  target_ep_id bigint;
  avg_val numeric(3, 1);
  vote_cnt integer;
begin
  if (TG_OP = 'DELETE') then
    target_ep_id := OLD.episode_id;
  else
    target_ep_id := NEW.episode_id;
  end if;

  select 
    coalesce(round(avg(rating)::numeric, 1), 0.0),
    count(*)
  into avg_val, vote_cnt
  from public.watchlistey_user_ratings
  where episode_id = target_ep_id;

  insert into public.aggregated_episode_rating_stats (
    episode_id,
    average_watchlistey_rating,
    watchlistey_votes,
    last_updated
  )
  values (
    target_ep_id,
    avg_val,
    vote_cnt,
    now()
  )
  on conflict (episode_id) do update set
    average_watchlistey_rating = excluded.average_watchlistey_rating,
    watchlistey_votes = excluded.watchlistey_votes,
    last_updated = now();

  return null;
end;
$$ language plpgsql security definer;

-- Trigger on user ratings
drop trigger if exists trg_recalculate_watchlistey_episode_stats on public.watchlistey_user_ratings;
create trigger trg_recalculate_watchlistey_episode_stats
after insert or update or delete on public.watchlistey_user_ratings
for each row execute function public.recalculate_watchlistey_episode_stats();

-- 6. Row Level Security (RLS)
alter table public.episodes enable row level security;
alter table public.external_ratings enable row level security;
alter table public.watchlistey_user_ratings enable row level security;
alter table public.aggregated_episode_rating_stats enable row level security;

-- Public Read Policies
create policy "Allow public read on episodes"
  on public.episodes for select using (true);

create policy "Allow public read on external_ratings"
  on public.external_ratings for select using (true);

create policy "Allow public read on watchlistey_user_ratings"
  on public.watchlistey_user_ratings for select using (true);

create policy "Allow public read on aggregated_episode_rating_stats"
  on public.aggregated_episode_rating_stats for select using (true);

-- Authenticated Write Policies for User Ratings
create policy "Allow users to insert their own episode rating"
  on public.watchlistey_user_ratings for insert
  with check (auth.uid() = user_id);

create policy "Allow users to update their own episode rating"
  on public.watchlistey_user_ratings for update
  using (auth.uid() = user_id);

create policy "Allow users to delete their own episode rating"
  on public.watchlistey_user_ratings for delete
  using (auth.uid() = user_id);

-- System / Authenticated Insert on episodes & external ratings for automatic sync
create policy "Allow authenticated/anon upsert on episodes"
  on public.episodes for all
  using (true)
  with check (true);

create policy "Allow authenticated/anon upsert on external_ratings"
  on public.external_ratings for all
  using (true)
  with check (true);

create policy "Allow authenticated/anon upsert on aggregated stats"
  on public.aggregated_episode_rating_stats for all
  using (true)
  with check (true);
